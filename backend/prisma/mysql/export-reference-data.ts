// Writes prisma/mysql/reference-data.sql: the rows the PostgreSQL migrations
// insert (company profile, number series, chart of accounts, system ledgers,
// account heads, the cash account …) as they stand after the last migration,
// as MySQL INSERTs. The MySQL init migration ends with them, so a MySQL
// install starts with exactly the data a PostgreSQL one does.
//
// Run against an empty PostgreSQL database that has had every migration
// applied and nothing else (no seed, no app use):
//
//   DATABASE_URL=postgresql://… npx prisma migrate deploy --config prisma7.config.ts
//   DATABASE_URL=postgresql://… npx tsx prisma/mysql/export-reference-data.ts
//
// When a later PostgreSQL migration inserts or changes reference rows, write
// the same change into that MySQL migration by hand.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import pg from 'pg';

const here = dirname(fileURLToPath(import.meta.url));

type Column = { name: string; type: string };

const quote = (text: string) => `'${text.replace(/\\/g, '\\\\').replace(/'/g, "''")}'`;

function literal(value: unknown, column: Column): string {
  if (value === null || value === undefined) return 'NULL';
  switch (column.type) {
    case 'boolean':
      return value ? '1' : '0';
    case 'smallint':
    case 'integer':
    case 'bigint':
    case 'numeric':
    case 'double precision':
    case 'real':
      return String(value);
    case 'json':
    case 'jsonb':
      return quote(JSON.stringify(value));
    case 'timestamp without time zone':
    case 'timestamp with time zone':
      // row_to_json gives 2026-11-03T05:30:00.123 (UTC, as Prisma stores it).
      return quote(String(value).replace('T', ' ').replace(/(Z|[+-]\d\d:\d\d)$/, ''));
    default:
      return quote(String(value));
  }
}

async function main() {
  const client = new pg.Client({ connectionString: process.env['DATABASE_URL'] });
  await client.connect();
  try {
    const tables = (
      await client.query<{ table_name: string }>(
        `SELECT table_name FROM information_schema.tables
         WHERE table_schema = 'public' AND table_type = 'BASE TABLE' AND table_name <> '_prisma_migrations'
         ORDER BY table_name`,
      )
    ).rows.map((row) => row.table_name);

    const parts: string[] = [];
    for (const table of tables) {
      const { rows } = await client.query<{ row: Record<string, unknown> }>(`SELECT row_to_json(t) AS row FROM "${table}" t ORDER BY row_to_json(t)::text`);
      if (rows.length === 0) continue;
      const columns = (
        await client.query<{ column_name: string; data_type: string }>(
          `SELECT column_name, data_type FROM information_schema.columns
           WHERE table_schema = 'public' AND table_name = $1 ORDER BY ordinal_position`,
          [table],
        )
      ).rows.map((row): Column => ({ name: row.column_name, type: row.data_type }));
      const names = columns.map((column) => `\`${column.name}\``).join(', ');
      const values = rows.map(({ row }) => `  (${columns.map((column) => literal(row[column.name], column)).join(', ')})`);
      parts.push(`-- ${table}\nINSERT INTO \`${table}\` (${names}) VALUES\n${values.join(',\n')};`);
    }

    const sql = [
      '-- GENERATED by export-reference-data.ts from the PostgreSQL migrations.',
      '-- The starting data every install has: see that script before editing.',
      'SET FOREIGN_KEY_CHECKS = 0;',
      '',
      parts.join('\n\n'),
      '',
      'SET FOREIGN_KEY_CHECKS = 1;',
      '',
    ].join('\n');
    writeFileSync(join(here, 'reference-data.sql'), sql);
    console.log(`Wrote prisma/mysql/reference-data.sql (${parts.length} tables)`);
  } finally {
    await client.end();
  }
}

await main();
